# -*- coding: utf-8 -*-
#@category AnyTone
# Ghidra Jython script, offline analysis only. No firmware patch is generated.
# Import D878.elf as a program first, then run this script.
# Optional script arg 1: full path for generated pseudocode text.
from ghidra.app.decompiler import DecompInterface
from java.io import File, PrintWriter

CANDIDATES = [
    ('orbital_math_candidate', 0x08077CC8),
    ('angular_math_candidate', 0x0807806C),
    ('position_handler_candidate', 0x080785BE),
    ('numeric_date_candidate', 0x08078620),
    ('ui_calling_position_candidate', 0x08049476),
    ('prediction_initializer_candidate', 0x0807A7A8),
    ('prediction_step_candidate', 0x08079C32),
    ('prediction_select_candidate', 0x08079A60),
    ('numeric_subroutine_candidate', 0x08078326),
]

args = getScriptArgs()
if args and len(args) > 0:
    outfile = File(args[0])
else:
    outfile = askFile('Choose output text for AnyTone decompilation', 'Save')

writer = PrintWriter(outfile, 'UTF-8')
decompiler = DecompInterface()
decompiler.toggleCCode(True)
decompiler.toggleSyntaxTree(True)
if not decompiler.openProgram(currentProgram):
    writer.println('Ghidra failed to open current program.')
    writer.close()
    raise RuntimeError('Cannot initialize decompiler')

writer.println('D878UVII PLUS v3.07: targeted Ghidra decompilation')
writer.println('Static analysis only. Function labels are hypotheses, not established names.')
writer.println('Base address expected 0x08004000; verify your imported ELF address map.')
writer.println('')

for label, address in CANDIDATES:
    addr = toAddr(address)
    writer.println('\n' + '='*76)
    writer.println('%s : %s' % (label, str(addr)))
    func = getFunctionAt(addr)
    if func is None:
        func = getFunctionContaining(addr)
        if func is not None:
            writer.println('NOTE: address is inside the function at %s' % str(func.getEntryPoint()))
    if func is None:
        try:
            func = createFunction(addr, 'candidate_' + str(hex(address))[2:])
        except Exception as exc:
            writer.println('Could not define function automatically: ' + str(exc))
    if func is None:
        writer.println('No function at this address. Check whether code/data is misclassified.')
        continue
    try:
        result = decompiler.decompileFunction(func, 90, monitor)
        if not result.decompileCompleted():
            writer.println('Decompilation error: ' + str(result.getErrorMessage()))
        elif result.getDecompiledFunction() is not None:
            writer.println(result.getDecompiledFunction().getC())
        else:
            writer.println('No C pseudo-code returned.')
        writer.println('\nCross-references to function entry:')
        refs = getReferencesTo(func.getEntryPoint())
        for i, ref in enumerate(refs):
            if i >= 80:
                writer.println('(truncated after 80 references)')
                break
            writer.println('  %s -> %s (%s)' % (str(ref.getFromAddress()),str(ref.getToAddress()),str(ref.getReferenceType())))
    except Exception as exc:
        writer.println('Analysis failed: ' + str(exc))

writer.println('\nManual next step: trace satellite UI to frequency RX/TX setters and timer; validate timing and PTT gating.')
writer.println('NO HEX/CDD is generated by this script.')
writer.close()
decompiler.dispose()
print('Wrote analysis to ' + outfile.getAbsolutePath())
